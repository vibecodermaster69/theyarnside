create table public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  description text,
  category text not null,
  price_inr integer not null check (price_inr >= 0),
  image_url text,
  image_urls jsonb not null default '[]'::jsonb,
  dimensions text,
  weight_grams integer check (weight_grams is null or weight_grams >= 0),
  stock_quantity integer not null default 0 check (stock_quantity >= 0),
  is_new boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.orders (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  customer_email text,
  customer_phone text not null,
  delivery_address text not null,
  notes text,
  status text not null default 'new' check (status in ('new', 'contacted', 'payment_pending', 'paid', 'making', 'shipped', 'completed', 'cancelled')),
  total_inr integer not null default 0 check (total_inr >= 0),
  pickup_status text not null default 'not_requested' check (pickup_status in ('not_requested', 'requested', 'picked_up')),
  pickup_requested_at timestamptz,
  shiprocket_order_id text,
  shiprocket_shipment_id text,
  awb_code text,
  courier_name text,
  tracking_url text,
  stock_restored_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  product_id bigint not null references public.products(id),
  product_name text not null,
  quantity integer not null check (quantity > 0),
  unit_price_inr integer not null check (unit_price_inr >= 0),
  created_at timestamptz not null default now()
);

create table public.order_requests (
  id bigint generated by default as identity primary key,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  quantity integer not null check (quantity > 0),
  customer_name text not null,
  phone text not null,
  shipping_address text not null,
  budget_inr integer not null check (budget_inr >= 0),
  timeframe text not null check (timeframe in ('2_weeks', '3_weeks', '4_weeks', '5_weeks', 'take_your_time')),
  notes text,
  policy_version text,
  policy_accepted_at timestamptz,
  status text not null default 'new' check (status in ('new', 'contacted', 'accepted', 'declined', 'completed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

